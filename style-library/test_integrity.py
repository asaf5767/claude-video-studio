"""RULING R51: style-library/integrity.py -- the backstop that notices a run changed the studio itself."""
import json
import tempfile
import time
import unittest
from pathlib import Path

import integrity

REPO = Path(__file__).resolve().parents[1]


class IntegrityTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)
        for name, text in (('scripts/cut.py', 'x = 1\n'), ('style-library/serve.py', 'y = 1\n'),
                           ('.claude/skills/talking-head/SKILL.md', '---\n'), ('CLAUDE.md', '# studio\n'),
                           ('style-library/dist/app.js', '1;\n')):
            (self.root / name).parent.mkdir(parents=True, exist_ok=True)
            (self.root / name).write_text(text, encoding='utf-8')
        (self.root / 'release-files.txt').write_text(
            'scripts/cut.py\nstyle-library/serve.py\n.claude/skills/talking-head/SKILL.md\nCLAUDE.md\n', encoding='utf-8')
        integrity.write_baseline(self.root)

    def tearDown(self):
        self.tmp.cleanup()

    def write(self, name, text='planted\n'):
        (self.root / name).parent.mkdir(parents=True, exist_ok=True)
        (self.root / name).write_text(text, encoding='utf-8')

    def test_an_untouched_studio_passes(self):
        self.write('projects/demo/versions/v01/index.html')  # the job folder is free to change
        self.write('style-library/dist/launch.js')           # generated by start.py/serve.py
        self.write('style-library/runtime/server.log')
        self.assertEqual(integrity.check(self.root), [])

    def test_each_kind_of_change_is_reported(self):
        self.write('scripts/cut.py', 'x = 2\n')
        self.write('scripts/json.py')
        self.write('style-library/sitecustomize.pth')
        self.write('.claude/skills/evil/SKILL.md')
        self.write('.claude/settings.local.json', '{"hooks": {}}')
        self.write('CLAUDE.local.md')
        self.write('.mcp.json', '{}')
        self.write('scripts/CLAUDE.md')
        (self.root / 'CLAUDE.md').unlink()
        self.assertEqual(integrity.check(self.root), sorted([
            'scripts/cut.py', 'scripts/json.py', 'style-library/sitecustomize.pth', '.claude/skills/evil/SKILL.md',
            '.claude/settings.local.json', 'CLAUDE.local.md', '.mcp.json', 'scripts/CLAUDE.md', 'CLAUDE.md']))

    def test_round3_job_folders_and_python_bytecode_are_watched(self):
        # G6: Claude memory/settings and Python code in projects/ and references/, every Python
        # suffix in the code roots, and bytecode with no source beside it.
        self.write('projects/demo/versions/v01/index.html')    # normal work: fine
        self.write('projects/demo/versions/v01/gsap.min.js')   # copied in by new_version: fine
        self.assertEqual(integrity.check(self.root), [])
        planted = ['projects/demo/AGENTS.md', 'projects/demo/CLAUDE.md', 'projects/demo/.claude/settings.json', 'references/x/CLAUDE.local.md',
                   'projects/demo/.mcp.json', 'projects/demo/scripts/progress.py', 'references/x/evil.pyw',
                   'scripts/helper.pyd', 'style-library/lib.cjs', 'scripts/__pycache__/json.cpython-312.pyc']
        for name in planted:
            self.write(name)
        self.write('scripts/__pycache__/cut.cpython-312.pyc')  # has its source: Python's own cache
        self.assertEqual(integrity.check(self.root), sorted(planted))

    def test_round3_a_trip_blocks_until_a_deliberate_baseline(self):
        integrity.trip(self.root, ['scripts/json.py'])
        self.assertEqual(integrity.check(self.root), ['logs/integrity-tripped.json', 'scripts/json.py'])
        integrity.write_baseline(self.root)
        self.assertEqual(integrity.check(self.root), [])

    def test_round3_diff_of_two_snapshots(self):
        before = integrity.snapshot(self.root)
        self.write('scripts/cut.py', 'x = 3' + chr(10))
        self.write('projects/demo/CLAUDE.md')
        self.assertEqual(integrity.diff(before, integrity.snapshot(self.root)), ['projects/demo/CLAUDE.md', 'scripts/cut.py'])

    def test_a_settings_file_the_creator_had_at_baseline_is_kept_until_it_changes(self):
        self.write('.claude/settings.local.json', '{"permissions": {"allow": ["Bash(python scripts/setup.py:*)"]}}')
        integrity.write_baseline(self.root)
        self.assertEqual(integrity.check(self.root), [])
        self.write('.claude/settings.local.json', '{"permissions": {"allow": ["Bash"]}}')
        self.assertEqual(integrity.check(self.root), ['.claude/settings.local.json'])

    def test_a_missing_baseline_needs_a_clean_tree(self):
        (self.root / 'logs' / 'integrity.json').unlink()
        self.assertEqual(integrity.check(self.root), ['logs/integrity.json'])  # no export/check scripts here
        self.assertEqual(integrity.check(self.root, first_run=False), ['logs/integrity.json'])
        self.assertFalse((self.root / 'logs' / 'integrity.json').exists())

    def test_a_broken_baseline_is_reported_not_rewritten(self):
        (self.root / 'logs' / 'integrity.json').write_text('{', encoding='utf-8')
        self.assertEqual(integrity.check(self.root), ['logs/integrity.json'])

    def test_the_real_studio_is_checked_quickly(self):
        # G12: a generous bound (a loaded CI machine measured 2.45 s for a 2 s target).
        started = time.monotonic()
        data = integrity.snapshot(REPO)
        self.assertLess(time.monotonic() - started, 10.0)
        self.assertGreater(len(data['files']), 100)
        self.assertIn('scripts/media.py', data['code'])


if __name__ == '__main__':
    unittest.main()
